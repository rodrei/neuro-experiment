# Console chat to try the prompts without opening PsychoPy
# =====================================================================
if __name__ == "__main__":
    feedback = ""
    while feedback not in FEEDBACK_TYPES:
        feedback = input("Feedback type? (validation/rejection): ").strip()
    topics = protocol.topics()
    for i, t in enumerate(topics, 1):
        print("%d. %s" % (i, t["question"]))
    choice = input("Topic number (Enter for the situation prompt): ").strip()
    if choice.isdigit() and 1 <= int(choice) <= len(topics):
        question = topics[int(choice) - 1]["question"]
        agent = LLMAgent(feedback, name="Nova", question=question)
        print("\n[topic] %s" % question)
    else:
        agent = LLMAgent(feedback)
        greeting = ("Hola. Me dijeron que vamos a charlar un rato. Contame algo "
                    "que te haya pasado últimamente y que te haya movilizado.")
        agent.greet(greeting)
        print("\n[agent] %s" % greeting)
    fallback = protocol.fallback_lines()[feedback]
    turn = 0
    while True:
        try:
            line = input("\n[you] ").strip()
        except (EOFError, KeyboardInterrupt):
            break
        if not line:
            break
        agent.hear(line)
        turn += 1
        text, origin, reason = agent.reply(
            fallback_line=fallback.get(min(turn, 3), "(fallback)"))
        print("\n[agent · %s%s] %s"
              % (origin, (" · " + reason) if reason else "", text))
