# -*- coding: utf-8 -*-
"""
LLM conversational agent (OpenRouter).

On the web it is the only agent: every episode's turns are generated by the
model from the debate prompt (protocol/prompts.json, `debate`), with the
participant's chosen question and the interlocutor's name in the system
prompt. On the desktop it is opt-in (AGENT = "llm" in the desktop config)
and uses the `situation` prompt.

Key decisions:
  - If the API fails or returns nothing, the turn falls back to a fixed line
    (protocol/fallback.csv on the web, protocol/scripts.csv on the desktop)
    and the experiment goes on: it never crashes. The origin AND the reason
    are returned, so the failure is visible and recorded.
  - The key is read from OPENROUTER_API_KEY or from openrouter_key.txt
    (gitignored), because there are no environment variables when launching
    from PsychoPy Coder.
  - No new dependencies: only urllib from the standard library.

To iterate on the prompts without opening PsychoPy:  python3 -m common.llm_agent
"""

import json
import os
import ssl
import threading
import time
import urllib.error
import urllib.request

from common import protocol

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OPENROUTER_URL = "https://openrouter.ai/api/v1/chat/completions"

FEEDBACK_TYPES = ("validation", "rejection")

# The timeout is operational, not methodological: each platform passes it
# when building the agent. This is the value used when nobody says otherwise.
DEFAULT_TIMEOUT = 20


def _script_examples(feedback):
    """The scripted lines of the feedback type, as style anchors for the
    situation prompt."""
    try:
        return list(protocol.scripts()[feedback].values())
    except (OSError, KeyError):
        return []


def build_system_prompt(feedback, name=None, question=None):
    """The system prompt for one episode.

    With a `question` it is the debate prompt (web): the interlocutor's name,
    the chosen question and the role. Without one it is the situation prompt
    (desktop), anchored with the scripted lines as style examples.
    """
    if feedback not in FEEDBACK_TYPES:
        raise ValueError("feedback must be one of %s" % (FEEDBACK_TYPES,))
    cfg = protocol.prompts()
    if question is not None:
        block = cfg["debate"]
        return block["rules"].format(
            name=name or protocol.texts()["agent_name"],
            question=question,
            role=block["role"][feedback],
            max_chars=cfg["max_chars"])
    block = cfg["situation"]
    return block["rules"].format(
        name=name or protocol.texts()["agent_name"],
        role=block["role"][feedback],
        max_chars=cfg["max_chars"],
        examples="\n".join("- " + e for e in _script_examples(feedback))
                 or "(no examples)")


NO_REPLY_MARK = "(no responde)"


def clean_reply(text, max_chars):
    """Makes the text ready for a chat bubble: one line and, if it exceeds
    the maximum, cut at the last sentence end that fits.

    It also strips a leading "(no responde)": when the person does not answer
    we pass that mark to the model as if it were their message, and sometimes
    the model repeats it when starting its turn. Showing it on screen gives
    the scaffolding away.
    """
    text = " ".join(text.split())
    while text.lower().startswith(NO_REPLY_MARK):
        text = text[len(NO_REPLY_MARK):].lstrip(" .,:;-—")
    if len(text) <= max_chars:
        return text
    cut = text[:max_chars]
    last = max(cut.rfind("."), cut.rfind("!"), cut.rfind("?"))
    if last > 0:
        return cut[:last + 1]
    return cut


def load_api_key(folder=ROOT):
    """OPENROUTER_API_KEY from the environment, or openrouter_key.txt in `folder`."""
    key = os.environ.get("OPENROUTER_API_KEY", "").strip()
    if key:
        return key
    path = os.path.join(folder, "openrouter_key.txt")
    try:
        with open(path, encoding="utf-8") as f:
            key = f.read().strip()
    except OSError:
        return None
    return key or None


def api_key_source(folder=ROOT):
    """"env", "file" or None: where load_api_key() would find the key."""
    if os.environ.get("OPENROUTER_API_KEY", "").strip():
        return "env"
    if load_api_key(folder):
        return "file"
    return None


def _ssl_context():
    """TLS context built with a certificate authority that exists in this
    interpreter.

    PsychoPy's embedded Python does not have the certificate bundle where
    OpenSSL looks for it, so the default context cannot validate OpenRouter.
    certifi ships inside PsychoPy; if it is missing, the system bundle is
    used. Verification is never disabled: what the participant writes travels
    over this channel.
    """
    candidates = []
    try:
        import certifi
    except ImportError:
        pass
    else:
        candidates.append(certifi.where())
    candidates.append("/etc/ssl/cert.pem")
    for path in candidates:
        if os.path.exists(path):
            return ssl.create_default_context(cafile=path)
    return ssl.create_default_context()


def _raise_readable(error):
    """Turns an HTTPError into a RuntimeError whose message says the status
    and the start of the body: "HTTP 401 Unauthorized: {...}". Without this
    the reason recorded for a fallback would be just "HTTP Error 401"."""
    try:
        body = error.read().decode("utf-8", "replace")
    except Exception:
        body = ""
    raise RuntimeError("HTTP %d %s: %s" % (error.code, error.reason,
                                           " ".join(body.split())[:160]))


def _openrouter_transport(payload, timeout=DEFAULT_TIMEOUT):
    """Real transport: sends the payload and returns the reply text.

    Any problem (no key, no network, HTTP != 200, odd JSON) is left to
    propagate as an exception: the caller decides to fall back.
    """
    key = load_api_key()
    if not key:
        raise RuntimeError(
            "No API key: set OPENROUTER_API_KEY or create openrouter_key.txt")
    request = urllib.request.Request(
        OPENROUTER_URL,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Authorization": "Bearer " + key,
                 "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(request, timeout=timeout,
                                    context=_ssl_context()) as resp:
            data = json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as error:
        _raise_readable(error)
    return data["choices"][0]["message"]["content"]


def probe(transport=None, timeout=None):
    """Checks that the model answers: a one-token completion.

    Returns (ok, latency_s, error). `error` is "<Type>: <message>" when it
    failed, else None. Used by the web health check before a session starts.
    """
    cfg = protocol.prompts()
    if transport is None:
        t = DEFAULT_TIMEOUT if timeout is None else timeout
        transport = lambda payload: _openrouter_transport(payload, t)
    payload = {
        "model": cfg["model"],
        "messages": [{"role": "user", "content": "hola"}],
        "max_tokens": 1,
    }
    start = time.time()
    try:
        transport(payload)
    except Exception as error:
        return False, time.time() - start, "%s: %s" % (type(error).__name__, error)
    return True, time.time() - start, None


class LLMAgent(object):
    """One conversation episode. Build a new one per episode."""

    def __init__(self, feedback, transport=None, timeout=None,
                 name=None, question=None):
        if feedback not in FEEDBACK_TYPES:
            raise ValueError("feedback must be one of %s" % (FEEDBACK_TYPES,))
        self.feedback = feedback
        self.timeout = DEFAULT_TIMEOUT if timeout is None else timeout
        # The injected transport receives only the payload: the timeout is
        # bound here so the tests' signature does not change.
        if transport is None:
            transport = lambda payload: _openrouter_transport(
                payload, self.timeout)
        self.transport = transport
        self.history = []     # [{"role": ..., "content": ...}]
        self.system = build_system_prompt(feedback, name=name, question=question)

    # -----------------------------------------------------------------
    def greet(self, text):
        """Records a scripted agent message (e.g. the greeting)."""
        self.history.append({"role": "assistant", "content": text})

    def hear(self, text):
        """Records what the participant wrote."""
        self.history.append({"role": "user", "content": text})

    def reply(self, fallback_line):
        """Generates the next turn. Returns (text, origin, reason): origin is
        "llm" or "fallback", and reason is None on success or a short string
        saying why the turn fell back. If anything fails the turn comes from
        the fallback line and the history stays consistent with what was
        shown on screen."""
        cfg = protocol.prompts()
        payload = {
            "model": cfg["model"],
            "messages": [{"role": "system", "content": self.system}]
                        + list(self.history),
            "max_tokens": cfg["max_tokens"],
            "temperature": cfg["temperature"],
        }
        reason = None
        try:
            raw = self.transport(payload)
            text = clean_reply(raw, cfg["max_chars"])
        except Exception as error:
            text = ""
            reason = "%s: %s" % (type(error).__name__, error)
        origin = "llm"
        if not text.strip():
            reason = reason or "empty reply from model"
            # Without this notice an expired key, a network outage and a
            # certificate problem all look the same from the screen.
            print("LLM fallback (%s): %s" % (self.feedback, reason))
            text, origin = fallback_line, "fallback"
        self.history.append({"role": "assistant", "content": text})
        return text, origin, reason

    def reply_in_thread(self, fallback_line):
        """Like reply(), but in a thread: lets the screen keep drawing while
        the API is awaited. Returns a PendingReply."""
        return PendingReply(self, fallback_line)


class PendingReply(object):
    """A reply() running in the background."""

    def __init__(self, agent, fallback_line):
        self._result = None
        self._thread = threading.Thread(
            target=self._run, args=(agent, fallback_line), daemon=True)
        self._thread.start()

    def _run(self, agent, fallback_line):
        self._result = agent.reply(fallback_line)

    def ready(self):
        return not self._thread.is_alive()

    def result(self):
        """Blocks until the (text, origin, reason) is available."""
        self._thread.join()
        return self._result


